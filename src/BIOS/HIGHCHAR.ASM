; Shared high completion/helper bindings for the complete character owner.
.8086
BIOSHIGH SEGMENT BYTE PUBLIC 'BIOSHIGH'
ASSUME CS:BIOSHIGH
EXTRN BIOS_LOW_EXIT_ENTRY:DWORD, BIOS_LOW_BUSY_ENTRY:DWORD
EXTRN BIOS_LOW_CMDERR_ENTRY:DWORD, BIOS_LOW_ERRCNT_ENTRY:DWORD
EXTRN BIOS_LOW_ERREXIT_ENTRY:DWORD, BIOS_SERVICE_NEAR_CALL_GATE:DWORD
EXTRN BIOS_CHAR_GETDX_OFFSET:WORD, BinToBCD:WORD, DaycntToDay:WORD
PUBLIC BIOS_CHAR_EXIT, BIOS_CHAR_BUSY, BIOS_CHAR_CMDERR
PUBLIC BIOS_CHAR_ERRCNT, BIOS_CHAR_ERREXIT, BIOS_CHAR_GETDX
PUBLIC BIOS_CHAR_BINTOBCD, BIOS_CHAR_DAYCNTTODAY
BIOS_CHAR_EXIT:
        jmp dword ptr cs:[BIOS_LOW_EXIT_ENTRY]
BIOS_CHAR_BUSY:
        jmp dword ptr cs:[BIOS_LOW_BUSY_ENTRY]
BIOS_CHAR_CMDERR:
        jmp dword ptr cs:[BIOS_LOW_CMDERR_ENTRY]
BIOS_CHAR_ERRCNT:
        jmp dword ptr cs:[BIOS_LOW_ERRCNT_ENTRY]
BIOS_CHAR_ERREXIT:
        jmp dword ptr cs:[BIOS_LOW_ERREXIT_ENTRY]
BIOS_CHAR_GETDX:
        push word ptr cs:[BIOS_CHAR_GETDX_OFFSET]
        call dword ptr cs:[BIOS_SERVICE_NEAR_CALL_GATE]
        ret
BIOS_CHAR_BINTOBCD:
        push word ptr ds:[BinToBCD]
        call dword ptr cs:[BIOS_SERVICE_NEAR_CALL_GATE]
        ret
BIOS_CHAR_DAYCNTTODAY:
        push word ptr ds:[DaycntToDay]
        call dword ptr cs:[BIOS_SERVICE_NEAR_CALL_GATE]
        ret
BIOSHIGH ENDS
END

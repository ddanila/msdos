; The following are all of the segments used in the load order

CODERES 	SEGMENT PUBLIC BYTE	;AC000; resident code
CODERES 	ENDS

DATARES 	SEGMENT PUBLIC BYTE	;AC000; resident data
DATARES 	ENDS

IFDEF COMMAND_HIGH_RESIDENT
FORMATDATA SEGMENT PUBLIC BYTE
FORMATDATA ENDS
SHELLCODE SEGMENT PUBLIC BYTE
SHELLCODE ENDS
ENDIF

HMACODE 	SEGMENT PUBLIC BYTE	; low fallback; copied to DOS-owned HMA
HMACODE 	ENDS

MSGOPT 		SEGMENT PUBLIC BYTE	; optional /MSG resident catalogs
MSGOPT 		ENDS

IFDEF COMMAND_HIGH_RESIDENT
SHELLFIX SEGMENT PUBLIC WORD
SHELLFIX ENDS
ENDIF

BATARENA	SEGMENT PUBLIC PARA	;AC000; space for DOS ALLOCATE header
BATARENA	ENDS

BATSEG		SEGMENT PUBLIC PARA	;AC000; AUTOEXEC batch segment
BATSEG		ENDS

ENVARENA	SEGMENT PUBLIC PARA	;AC000; space for DOS ALLOCATE header
ENVARENA	ENDS

ENVIRONMENT	SEGMENT PUBLIC PARA	;AC000; Default COMMAND environment
ENVIRONMENT	ENDS

INIT		SEGMENT PUBLIC PARA	;AC000; Initialization code
INIT		ENDS

TAIL		SEGMENT PUBLIC PARA	;AC000; End of Init - start of Transient
TAIL		ENDS

TRANCODE	SEGMENT PUBLIC BYTE	;AC000; Transient code
TRANCODE	ENDS

TRANDATA	SEGMENT PUBLIC BYTE	;AC000; Transient data area
TRANDATA	ENDS

TRANSPACE	SEGMENT PUBLIC BYTE	;AC000; Transient modifiable data area
TRANSPACE	ENDS

TRANEXT		SEGMENT PUBLIC BYTE	; DOS 5 extensions after legacy workspace
TRANEXT		ENDS

TRANTAIL	SEGMENT PUBLIC PARA	;AC000; End of Transient
TRANTAIL	ENDS

	IFDEF COMMAND_HIGH_RESIDENT
RESGROUP GROUP CODERES,DATARES,FORMATDATA,SHELLCODE,HMACODE,MSGOPT,SHELLFIX,BATARENA,BATSEG,ENVARENA,ENVIRONMENT,INIT,TAIL
	ELSE
RESGROUP  GROUP CODERES,DATARES,HMACODE,MSGOPT,BATARENA,BATSEG,ENVARENA,ENVIRONMENT,INIT,TAIL
	ENDIF
TRANGROUP GROUP TRANCODE,TRANDATA,TRANSPACE,TRANEXT,TRANTAIL
IFDEF COMMAND_UMB_DATA
 IFNDEF COMMAND_HIGH_RESIDENT
  .ERR <upper shell data requires whole high resident layout>
 ENDIF
TRANSPACE SEGMENT PUBLIC BYTE
 EXTERNDEF RESDATA:WORD
TRANSPACE ENDS
DATARES SEGMENT PUBLIC BYTE
 EXTERNDEF MYSEG:WORD
DATARES ENDS
 SHELL_DATA_SELECTOR TEXTEQU <RESDATA>
ELSE
 SHELL_DATA_SELECTOR TEXTEQU <RESSEG>
ENDIF

